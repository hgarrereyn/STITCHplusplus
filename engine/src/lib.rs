use libafl_bolts::rands::{Rand, StdRand};
use std::ffi::{c_char, c_int, CStr, CString};
use std::path::PathBuf;
use std::time::Duration;

const USAGE: &str = "\
usage: fuzzer <command> [options]

commands:
  manifest                         print the harness manifest (JSON)
  fuzz --out DIR [options]         run a campaign
       --data DIR                    harness/data folder (seeds, dictionaries)
       --secs N                      stop after N seconds (default: run until killed)
       --seed N                      RNG seed
       --timeout-ms N                per-execution timeout (default 2000)
       --max-nodes N                 max calls per program (default 24)
       --only a,b,c                  endpoints the fuzzer may add on its own (producers are always allowed)
       --import DIR                  also load programs from DIR (repeatable)
       --sync DIR                    periodically import new programs from DIR (sibling workers)
       --persistent N                programs per forked worker (default 200; 0 = fork per program)
  exec [--trace] [--cmplog] FILE...  run programs in this process (--cmplog: print comparisons per call)
  triage --crashes DIR             bucket crashing programs by signature (JSON)
  minimize FILE -o OUT             reduce a crashing program, keeping its signature
  sample TYPE [-n N] [--seed S]    print values generated by a datatype decoder
  gen [-n N] -o DIR                write random programs (debugging)
";

fn init_manifest() -> Result<(), String> {
    let m = manifest::Manifest::parse(&ffi::manifest_json())?;
    manifest::init(m);
    Ok(())
}

fn arg_val(args: &[String], name: &str) -> Option<String> {
    args.iter().position(|a| a == name).and_then(|i| args.get(i + 1).cloned())
}

fn arg_all(args: &[String], name: &str) -> Vec<String> {
    let mut out = vec![];
    for (i, a) in args.iter().enumerate() {
        if a == name {
            if let Some(v) = args.get(i + 1) {
                out.push(v.clone());
            }
        }
    }
    out
}

fn positional(args: &[String], with_values: &[&str]) -> Vec<String> {
    let mut out = vec![];
    let mut i = 0;
    while i < args.len() {
        if args[i].starts_with('-') {
            if with_values.contains(&args[i].as_str()) {
                i += 1;
            }
        } else {
            out.push(args[i].clone());
        }
        i += 1;
    }
    out
}

fn setup_gen(args: &[String]) -> Result<(), String> {
    let m = manifest::get();
    let max_nodes = arg_val(args, "--max-nodes").and_then(|v| v.parse().ok()).unwrap_or(24usize).min(ffi::MAX_NODES);
    let mut selected = vec![true; m.endpoints.len()];
    if let Some(only) = arg_val(args, "--only") {
        let pats: Vec<&str> = only.split(',').map(|s| s.trim()).filter(|s| !s.is_empty()).collect();
        for (i, e) in m.endpoints.iter().enumerate() {
            selected[i] = pats.iter().any(|p| glob_match(p, &e.name) || glob_match(p, &e.file));
        }
        if !selected.iter().any(|&s| s) {
            return Err(format!("--only {only} matches no endpoint"));
        }
    }
    gen::init(gen::GenConfig { max_nodes, selected });
    Ok(())
}

/// Minimal glob: `*` matches any run of characters (including '/').
pub fn glob_match(pat: &str, s: &str) -> bool {
    fn rec(p: &[u8], s: &[u8]) -> bool {
        match (p.first(), s.first()) {
            (None, None) => true,
            (Some(b'*'), _) => rec(&p[1..], s) || (!s.is_empty() && rec(p, &s[1..])),
            (Some(a), Some(b)) if a == b => rec(&p[1..], &s[1..]),
            _ => false,
        }
    }
    rec(pat.as_bytes(), s.as_bytes()) || (!pat.contains('*') && s.contains(pat))
}

fn real_main(args: Vec<String>) -> Result<i32, String> {
    let cmd = args.first().cloned().unwrap_or_default();
    let rest = &args[args.len().min(1)..];
    match cmd.as_str() {
        "manifest" => {
            println!("{}", ffi::manifest_json());
            Ok(0)
        }
        "fuzz" => {
            // Sanitizer options are read at process start: re-exec once with fuzzing settings
            // (no symbolization of crash reports; triage re-runs crashes symbolized).
            if std::env::var_os("STITCH_FUZZ_REEXEC").is_none() {
                use std::os::unix::process::CommandExt;
                let exe = std::env::current_exe().map_err(|e| e.to_string())?;
                let asan = std::env::var("ASAN_OPTIONS").unwrap_or_default();
                let ubsan = std::env::var("UBSAN_OPTIONS").unwrap_or_default();
                let err = std::process::Command::new(exe)
                    .args(&args)
                    .env("STITCH_FUZZ_REEXEC", "1")
                    // small quarantine: parent + every worker would otherwise keep 256 MB of freed memory
                    .env("ASAN_OPTIONS", format!("{asan}:symbolize=0:print_summary=0:quarantine_size_mb=16:malloc_context_size=5"))
                    .env("UBSAN_OPTIONS", format!("{ubsan}:symbolize=0"))
                    .exec();
                return Err(format!("re-exec failed: {err}"));
            }
            if rest.iter().any(|a| a == "--quiet") {
                // children's sanitizer reports would flood the terminal; keep them out
                let devnull = std::fs::OpenOptions::new().write(true).open("/dev/null").map_err(|e| e.to_string())?;
                use std::os::fd::AsRawFd;
                unsafe { libc::dup2(devnull.as_raw_fd(), 2) };
            }
            init_manifest()?;
            setup_gen(rest)?;
            let out = PathBuf::from(arg_val(rest, "--out").ok_or("fuzz needs --out DIR")?);
            std::fs::create_dir_all(&out).map_err(|e| e.to_string())?;
            let data_dir = arg_val(rest, "--data").map(PathBuf::from);
            data::load(data_dir.as_deref());
            let seed = arg_val(rest, "--seed").and_then(|v| v.parse().ok()).unwrap_or_else(|| {
                std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos() as u64
            });
            let cfg = fuzz::FuzzConfig {
                out,
                secs: arg_val(rest, "--secs").and_then(|v| v.parse().ok()),
                seed,
                timeout_ms: arg_val(rest, "--timeout-ms").and_then(|v| v.parse().ok()).unwrap_or(2000),
                import: arg_all(rest, "--import").into_iter().map(PathBuf::from).collect(),
                sync: arg_all(rest, "--sync").into_iter().map(PathBuf::from).collect(),
                quiet: rest.iter().any(|a| a == "--quiet"),
                persistent: arg_val(rest, "--persistent").and_then(|v| v.parse().ok()).unwrap_or(200),
            };
            fuzz::run(cfg).map_err(|e| format!("fuzzer error: {e}"))?;
            Ok(0)
        }
        "exec" => {
            let trace = rest.iter().any(|a| a == "--trace");
            let want_cmplog = rest.iter().any(|a| a == "--cmplog");
            unsafe { ffi::stitch_init_once() };
            if want_cmplog {
                unsafe { ffi::stitch_cmplog_reset() };
                ffi::cmplog().enabled = 1;
            }
            for f in positional(rest, &[]) {
                if trace {
                    eprintln!("[stitch] running {f}");
                }
                let c = CString::new(f.clone()).unwrap();
                let rc = unsafe { ffi::stitch_run_file(c.as_ptr(), if trace { 1 } else { 0 }) };
                if rc != 0 {
                    return Err(format!("{f}: not a valid program for this harness"));
                }
            }
            if want_cmplog {
                let c = cmplog::collect();
                let mut nodes: Vec<_> = c.per_node.iter().collect();
                nodes.sort_by_key(|x| *x.0);
                for (n, recs) in nodes {
                    for r in recs {
                        let show = |v: &[u8]| -> String {
                            if r.kind == 1 { String::from_utf8_lossy(v).into_owned() } else { format!("{}", u64::from_le_bytes(v[..8].try_into().unwrap())) }
                        };
                        println!("node {n}: {} {:?} vs {:?}", if r.kind == 1 { "bytes" } else { "int" }, show(&r.a), show(&r.b));
                    }
                }
            }
            Ok(0)
        }
        "triage" => {
            init_manifest()?;
            let dir = PathBuf::from(arg_val(rest, "--crashes").ok_or("triage needs --crashes DIR")?);
            let t = arg_val(rest, "--timeout-ms").and_then(|v| v.parse().ok()).unwrap_or(10000);
            let b = triage::triage_dir(&dir, Duration::from_millis(t));
            println!("{}", serde_json::to_string_pretty(&b).unwrap());
            Ok(0)
        }
        "minimize" => {
            init_manifest()?;
            let pos = positional(rest, &["-o", "--secs", "--timeout-ms"]);
            let f = pos.first().ok_or("minimize needs FILE")?;
            let out = arg_val(rest, "-o").ok_or("minimize needs -o OUT")?;
            let prog = program::Program::deserialize(&std::fs::read(f).map_err(|e| e.to_string())?)
                .ok_or("not a valid program for this harness")?;
            let secs = arg_val(rest, "--secs").and_then(|v| v.parse().ok()).unwrap_or(120);
            let t = arg_val(rest, "--timeout-ms").and_then(|v| v.parse().ok()).unwrap_or(10000);
            let (min, rep) = triage::minimize(&prog, Duration::from_millis(t), Duration::from_secs(secs));
            std::fs::write(&out, min.serialize()).map_err(|e| e.to_string())?;
            println!(
                "{}",
                serde_json::json!({"crashes": rep.crashed, "signature": rep.signature, "calls_before": prog.nodes.len(), "calls_after": min.nodes.len(), "output": out})
            );
            Ok(0)
        }
        "sample" => {
            init_manifest()?;
            let m = manifest::get();
            let pos = positional(rest, &["-n", "--seed", "--data"]);
            let name = pos.first().ok_or("sample needs a datatype name")?;
            let dt = m.datatype_names.iter().position(|d| d == name).ok_or_else(|| format!("unknown datatype {name}; known: {:?}", m.datatype_names))?;
            data::load(arg_val(rest, "--data").map(PathBuf::from).as_deref());
            let n: usize = arg_val(rest, "-n").and_then(|v| v.parse().ok()).unwrap_or(5);
            let mut r = StdRand::with_seed(arg_val(rest, "--seed").and_then(|v| v.parse().ok()).unwrap_or(1));
            let mut out = vec![];
            for _ in 0..n {
                if m.datatype_decoder[dt] {
                    let ch = ffi::generate(dt, r.next(), &[], 4096);
                    let v = ffi::decode(dt, &ch, 4096);
                    out.push(serde_json::json!({"value": String::from_utf8_lossy(&v), "choice_bytes": ch.len()}));
                } else {
                    let s = data::seeds(dt);
                    if s.is_empty() {
                        return Err(format!("{name} has no decoder and no seeds"));
                    }
                    let v = &s[gen::below(&mut r, s.len())];
                    out.push(serde_json::json!({"value": String::from_utf8_lossy(v), "seed": true}));
                }
            }
            println!("{}", serde_json::to_string_pretty(&out).unwrap());
            Ok(0)
        }
        "gen" => {
            init_manifest()?;
            setup_gen(rest)?;
            let n: usize = arg_val(rest, "-n").and_then(|v| v.parse().ok()).unwrap_or(5);
            let out = PathBuf::from(arg_val(rest, "-o").ok_or("gen needs -o DIR")?);
            std::fs::create_dir_all(&out).map_err(|e| e.to_string())?;
            health::init(1);
            data::load(arg_val(rest, "--data").map(PathBuf::from).as_deref());
            let mut r = StdRand::with_seed(arg_val(rest, "--seed").and_then(|v| v.parse().ok()).unwrap_or(1));
            for i in 0..n {
                let calls = 1 + gen::below(&mut r, 6);
                let p = gen::random_program(&mut r, calls);
                std::fs::write(out.join(format!("gen-{i:04}.stp")), p.serialize()).map_err(|e| e.to_string())?;
            }
            Ok(0)
        }
        "" | "-h" | "--help" | "help" => {
            eprint!("{USAGE}");
            Ok(0)
        }
        other => Err(format!("unknown command '{other}'\n{USAGE}")),
    }
}

#[no_mangle]
pub extern "C" fn stitch_engine_main(argc: c_int, argv: *const *const c_char) -> c_int {
    let mut args = vec![];
    for i in 1..argc as isize {
        let s = unsafe { CStr::from_ptr(*argv.offset(i)) };
        args.push(s.to_string_lossy().into_owned());
    }
    match real_main(args) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("error: {e}");
            1
        }
    }
}
