#!/usr/bin/env python3
"""Generate Sources/Stitch/Endpoints.swift: `endpoint` overloads for 0..MAX arguments (Swift has no
variadic generics usable here), with and without outputs, and the Stub types they return."""
from pathlib import Path

MAX = 12
out = [f"// Generated by gen_endpoints.py: endpoint overloads for 0 to {MAX} arguments, with and without outputs,",
       "// and the Stub types they return. A stub with more arguments does not compile; group values in a struct.", ""]
for n in range(MAX + 1):
    tp = ", ".join([f"A{i}" for i in range(n)] + ["R"])
    args = ", ".join(f"A{i}" for i in range(n))
    out += [f"public struct Stub{n}<{tp}>: AnyStub {{", "    public let name: String",
            f"    public let body: ({args}) throws -> R", "}", ""]
for n in range(MAX + 1):
    gens = [f"A{i}: StitchArg" for i in range(n)]
    args = ", ".join(f"A{i}" for i in range(n))
    specs = "[" + ", ".join(f"A{i}.spec" for i in range(n)) + "]"
    call = ", ".join(f"A{i}.make(c, ord[{i}])" for i in range(n))
    ordl = "let ord = ordinals(specs)" if n else "_ = ordinals(specs)"
    for ret in (True, False):
        g = gens + (["R: StitchRet"] if ret else [])
        generic = f"<{', '.join(g)}>" if g else ""
        r = "R" if ret else "Void"
        stub = f"Stub{n}<{', '.join([f'A{i}' for i in range(n)] + [r])}>"
        body = (f"try body({call}).store(c)" if ret else f"try body({call})")
        outs = "R.outputs" if ret else "[]"
        out += ["/// Register a stub. The closure's argument types are its signature.", "@discardableResult",
                f"public func endpoint{generic}(_ name: String, file: String = #filePath, _ body: @escaping ({args}) throws -> {r}) -> {stub} {{",
                f"    let specs: [Spec] = {specs}", f"    {ordl}",
                f"    return {stub}(name: register(name, file, specs, {outs}) {{ c in {body} }}, body: body)", "}", ""]
Path(__file__).with_name("Sources").joinpath("Stitch", "Endpoints.swift").write_text("\n".join(out).rstrip() + "\n")
